# ---------------------------------------------------------------------------
# Arrow3D — copy of block-DDA_Py/shape_model/gaussian_ellipsoid.py utility
# ---------------------------------------------------------------------------

class Arrow3D(FancyArrowPatch):
    def __init__(self, x, y, z, dx, dy, dz, *args, **kwargs):
        super().__init__((0, 0), (0, 0), *args, **kwargs)
        self._xyz = (x, y, z)
        self._dxdydz = (dx, dy, dz)

    def draw(self, renderer):
        x1, y1, z1 = self._xyz
        dx, dy, dz = self._dxdydz
        x2, y2, z2 = (x1 + dx, y1 + dy, z1 + dz)
        xs, ys, zs = proj_transform((x1, x2), (y1, y2), (z1, z2), self.axes.M)
        self.set_positions((xs[0], ys[0]), (xs[1], ys[1]))
        super().draw(renderer)

    def do_3d_projection(self, renderer=None):
        x1, y1, z1 = self._xyz
        dx, dy, dz = self._dxdydz
        x2, y2, z2 = (x1 + dx, y1 + dy, z1 + dz)
        xs, ys, zs = proj_transform((x1, x2), (y1, y2), (z1, z2), self.axes.M)
        self.set_positions((xs[0], ys[0]), (xs[1], ys[1]))
        return float(np.min(zs))


# ---------------------------------------------------------------------------
# Surface generators
# ---------------------------------------------------------------------------

def oblate_surface(r_ve: float, ab_ratio: float = 1.0,
                   bc_ratio: float = 3.0,
                   n_theta: int = 60, n_phi: int = 90):
    """Triangulated surface of a base ellipsoid with axes a:b:c.

    Convention: a >= b >= c, with (a*b*c) = r_ve**3.  The default
    (ab_ratio = 1, bc_ratio = 3) gives a:b:c = 3:3:1.
    """
    c = np.cbrt(r_ve ** 3 / (ab_ratio * bc_ratio ** 2))
    b = c * bc_ratio
    a = b * ab_ratio
    theta = np.linspace(0, np.pi, n_theta)
    phi   = np.linspace(0, 2 * np.pi, n_phi)
    th, ph = np.meshgrid(theta, phi, indexing='ij')
    x = a * np.sin(th) * np.cos(ph)
    y = b * np.sin(th) * np.sin(ph)
    z = c * np.cos(th)
    return _structured_to_triangles(x, y, z)


def doublet_surface(r_ve: float, gap_factor: float = 0.1,
                    n_theta: int = 50, n_phi: int = 60):
    """Two equal monomers (radius R = r_ve / 2^(1/3)) along x with a
    surface gap of `gap_factor * R`.
    """
    R = r_ve / np.cbrt(2.0)
    gap = gap_factor * R
    half_sep = R + gap / 2.0  # center-to-origin distance for each monomer
    theta = np.linspace(0, np.pi, n_theta)
    phi   = np.linspace(0, 2 * np.pi, n_phi)
    th, ph = np.meshgrid(theta, phi, indexing='ij')
    x_local = R * np.sin(th) * np.cos(ph)
    y_local = R * np.sin(th) * np.sin(ph)
    z_local = R * np.cos(th)

    out_v = []
    out_f = []
    for offset in (-half_sep, +half_sep):
        x = x_local + offset
        y = y_local
        z = z_local
        v, f = _structured_to_triangles_split(x, y, z, len(out_v))
        out_v.extend(v)
        out_f.extend(f)
    return np.asarray(out_v), np.asarray(out_f)


def gre_surface(r_ve: float, beta: float = 0.2,
                ab_ratio: float = 1.0, bc_ratio: float = 1.0,
                rng_seed: int = 7):
    """Gaussian random sphere (a = b = c spherical base ellipsoid)
    surface points generated by block-DDA_Py's gaussian_ellipsoid_shape_model.
    """
    model = gaussian_ellipsoid_shape_model(
        r_v_base=r_ve, ab_ratio=ab_ratio, bc_ratio=bc_ratio,
        beta=beta, wl_0=0.638, m_p_xyz=[1.5, 1.5, 1.5], dpl=17,
    )
    rng = np.random.default_rng(rng_seed)
    _, (x, y, z) = model.compute_r_points_on_GRE(rng)
    return _structured_to_triangles(x, y, z)


# ---------------------------------------------------------------------------
# Triangulation helpers for structured (theta, phi) surface grids
# ---------------------------------------------------------------------------

def _structured_to_triangles(x, y, z):
    """Convert a structured (n_theta, n_phi) surface grid to a flat
    vertex array + triangle face list, with periodic phi wrap-around."""
    v, f = _structured_to_triangles_split(x, y, z, 0)
    return np.asarray(v), np.asarray(f)


def _structured_to_triangles_split(x, y, z, vertex_offset: int):
    n_theta, n_phi = x.shape
    verts = []
    for i in range(n_theta):
        for j in range(n_phi):
            verts.append((x[i, j], y[i, j], z[i, j]))
    faces = []
    for i in range(n_theta - 1):
        for j in range(n_phi):
            jn = (j + 1) % n_phi  # wrap around in phi
            v00 = vertex_offset + i * n_phi + j
            v01 = vertex_offset + i * n_phi + jn
            v10 = vertex_offset + (i + 1) * n_phi + j
            v11 = vertex_offset + (i + 1) * n_phi + jn
            faces.append((v00, v10, v11))
            faces.append((v00, v11, v01))
    return verts, faces


# ---------------------------------------------------------------------------
# Per-panel rendering
# ---------------------------------------------------------------------------

def _render_panel(ax, vertices: np.ndarray, faces: np.ndarray,
                  axis_range: float, panel_label: str,
                  azim_deg: float, elev_deg: float):
    # Triangulated surface — opaque grey with thin black mesh edges
    # so the discretisation is visible (matches block-VIEM.jl viz).
    ax.plot_trisurf(vertices[:, 0], vertices[:, 1], vertices[:, 2],
                    triangles=faces,
                    color='lightsteelblue',
                    edgecolor=(0.15, 0.15, 0.15, 0.7),
                    linewidth=0.35,
                    shade=True, antialiased=True)

    # Lab-frame axis arrows via Arrow3D (block-DDA_Py convention).
    # Arrow length 0.92 * axis_range so it stays inside the bbox.
    L = 0.92 * axis_range
    arrow_kw = dict(mutation_scale=20, arrowstyle='-|>', lw=1.6)
    ax.add_artist(Arrow3D(0, 0, 0, L, 0, 0, ec='red',   fc='red',   **arrow_kw))
    ax.add_artist(Arrow3D(0, 0, 0, 0, L, 0, ec='blue',  fc='blue',  **arrow_kw))
    ax.add_artist(Arrow3D(0, 0, 0, 0, 0, L, ec='black', fc='black', **arrow_kw))

    ax.set_xlim(-axis_range, axis_range)
    ax.set_ylim(-axis_range, axis_range)
    ax.set_zlim(-axis_range, axis_range)
    ax.set_xlabel('x [μm]', fontsize=10, labelpad=2)
    ax.set_ylabel('y [μm]', fontsize=10, labelpad=2)
    ax.set_zlabel('z [μm]', fontsize=10, labelpad=2)
    ax.set_box_aspect((1, 1, 1))
    ax.view_init(elev=elev_deg, azim=azim_deg)
    ax.set_title(panel_label, fontsize=18, fontweight='bold', pad=2)
    ax.tick_params(axis='both', which='major', labelsize=9, pad=0)


# ---------------------------------------------------------------------------
# Combined 1x3 figure
# ---------------------------------------------------------------------------

def render_combined(out_path: Path, r_ve: float = 0.10):
    v_o, f_o = oblate_surface(r_ve)
    v_d, f_d = doublet_surface(r_ve)
    v_g, f_g = gre_surface(r_ve)

    # Common axis range: max extent across all three meshes, plus margin
    max_extent = max(
        np.max(np.abs(v_o)),
        np.max(np.abs(v_d)),
        np.max(np.abs(v_g)),
    )
    axis_range = max_extent * 1.15

    fig = plt.figure(figsize=(11.0, 4.4))

    # Panel layout: axes positioned manually (left, bottom, width, height)
    # in figure-fraction units, with explicit gaps between panels.
    panel_w = 0.30
    panel_h = 0.90
    bottom  = 0.04
    gap     = 0.025
    left0   = 0.025
    panels = [
        dict(rect=(left0,                   bottom, panel_w, panel_h),
             v=v_o, f=f_o, label='(a)', azim=-130, elev=20),
        dict(rect=(left0 + panel_w + gap,   bottom, panel_w, panel_h),
             v=v_d, f=f_d, label='(b)', azim=-80,  elev=20),
        dict(rect=(left0 + 2 * (panel_w + gap), bottom, panel_w, panel_h),
             v=v_g, f=f_g, label='(c)', azim=-130, elev=20),
    ]
    for p in panels:
        ax = fig.add_axes(p['rect'], projection='3d')
        _render_panel(ax, p['v'], p['f'], axis_range, p['label'],
                      azim_deg=p['azim'], elev_deg=p['elev'])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=200, bbox_inches=None)
    plt.close(fig)
    print(f'Wrote {out_path}  (axis_range = {axis_range:.4f} um)')


# ---------------------------------------------------------------------------
# CLI entry
# ---------------------------------------------------------------------------

if __name__ == '__main__':
    out = (Path(__file__).resolve().parent
           / 'figures' / 'fig1_target_geometries.pdf')
    render_combined(out)
