"""Render the lab-frame surface meshes of the three non-spherical paper
targets (oblate spheroid, sphere doublet, Gaussian random sphere) used
in Sec. 4.2 / 4.3 of the block-DDA_Py / block-VIEM.jl benchmark paper.

The figure is a 1x3 panel matplotlib figure with shared axis range.
Each panel shows a triangulated surface mesh in the laboratory frame
at the convergence-test orientation (alpha, beta, gamma) = (0, 0, 0)
and r_ve = 0.10 um, plus the lab-frame x/y/z arrows drawn via
matplotlib's Arrow3D (FancyArrowPatch projected to 3D), exactly the
same rendering used in block-DDA_Py/run_gaussian_ellipsoid.ipynb.

Output: dda_results/paper/figures/fig1_target_geometries.pdf
"""
from __future__ import annotations

